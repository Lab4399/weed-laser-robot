UART_TIMEOUT_MS = 100
UART_TX_PIN = None              # 例如 "P4"；留 None 用该 UART 默认引脚
UART_RX_PIN = None

# 心跳：即使没有目标也必须按此周期发帧，否则 F407 无法区分
# "看不到杂草" 和 "串口线断了"。这是安全设计，不是可选项。
HEARTBEAT_MS = 50

# ---------------------------------------------------------------------------
# 识别
# ---------------------------------------------------------------------------
DETECTOR = "blob"               # "fomo"（Edge Impulse 模型）或 "blob"（颜色阈值 POC）
MODEL_PATH = "/model.tflite"    # DETECTOR == "fomo" 时使用

# ⚠️ 2026-10-19 首次联调时改为 "blob"：
#    当前没有与 F407 新固件配套的 FOMO 检测模型（/model.tflite 不存在）。
#    仓库里的 *_int8.tflite 是**分类**模型（48×48 单目标），
#    与本文件要求的检测模型（tf.detect 输出多个框）不是一回事，不能直接替换。
#    blob 模式不依赖模型，用于先把"采集→组帧→UART→F407"整条链路跑通。
#    模型到位后改回 "fomo" 即可，其余代码无需改动。

CONF_MIN_SEND = 0.45            # 低于此置信度视为无目标，不发目标帧
CONF_MIN_TRACK = 0.60           # 低于此置信度不允许产生激进运动（F407 侧二次判定）

# blob 方案（仅 POC 用）：LAB 阈值列表，每项 (name, (Lmin,Lmax,Amin,Amax,Bmin,Bmax))
BLOB_THRESHOLDS = [
    ("WEED", (0, 55, -30, 40, -10, 60)),   # 深绿偏暗：需按实际光照重标定
]

# ---------------------------------------------------------------------------
# 目标选择（多个候选时选谁）
# ---------------------------------------------------------------------------
# 评分 = CONF_W * 置信度 + AREA_W * 归一化面积 - CENTER_W * 归一化离中心距离
