# ---------------------------------------------------------------------------
# 云台舵机（视觉内环，由 OpenMV 直接控制）
# ---------------------------------------------------------------------------
# ⚠️ 2026-10-19 首次联调时改为 False：
#    F407 侧 TIM3 也在输出 50 Hz 舵机 PWM。在接线未核实之前让 OpenMV 同时
#    驱动 pyb.Servo，等于两个主控争同一路信号 —— 轻则不动作，重则舵机堵转
#    发热。确认云台到底接在哪一侧之后，再把本项改回 True。
GIMBAL_ENABLE = False
GIMBAL_SERVO_ID = 1             # pyb.Servo 编号，按实际接线确认
GIMBAL_ANGLE_MIN = -30          # 机械限位，必须先手动验证再填入
GIMBAL_ANGLE_MAX = 30
GIMBAL_ANGLE_HOME = 0

GIMBAL_KP = 0.035               # 角度/像素。过大会自激振荡，见下方说明
GIMBAL_DEADZONE_PX = 18         # 误差小于此值不动舵机
GIMBAL_MAX_STEP_DEG = 4         # 单次最大转动，限制冲击
GIMBAL_SETTLE_MS = 120          # 舵机动作后停止更新，等画面稳定

# 为什么需要 SETTLE：
# 舵机转动 → 摄像头视角变化 → 目标在画面中位移 → 误差"看起来"变了，
# 但这个位移是舵机自己造成的。若不做冷却，会形成正反馈自激振荡。
# 这是云台视觉闭环最常见的失效模式。

